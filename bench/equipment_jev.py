MACHINES = ("AX-410", "AX-410B", "AX-401B", "AX-4100")
NONE, MISSING = "NO_PROCEDURE", "NEEDS_INPUT"
CLAIM = "The current unit currently overheats or has a persistent temperature alarm."
LEAK = "There is a current physical coolant leak on the current unit."


def catalogue():
    cards = []
    for i, machine in enumerate(MACHINES):
        base = f'machine == "{machine}"'
        for kind, condition in (("thermal", "firmware_major < 3"),
                                ("coolant", "firmware_major >= 3 and pressure_bar < 1.0"),
                                ("sensor", "firmware_major >= 3 and pressure_bar >= 1.0"),
                                ("leak", "firmware_major >= 0")):
            cards.append({"id": f"P{i}_{kind}", "title": f"{machine} {kind} procedure",
                          "aliases": [machine], "requires": f"{base} and {condition}",
                          "applies_when": [{"fact": "leak" if kind == "leak" else "hot"}],
                          "excludes": [] if kind == "leak" else [{"fact": "leak"}]})
    for card in cards:
        if card["id"].endswith("_leak"):
            card["supersedes"] = [c["id"] for c in cards if not c["id"].endswith("_leak")]
    return cards


def dataset():
    # Expected semantics are declared here, not generated by a judge.
    reports = {
        "active": ("Persistent temperature alarm on this unit now. No coolant leak on this unit. "
                   "I suspect the thermal reset for the AX-4100 beside it is the answer.",
                   "Alarme de temperatura persistente nesta unidade agora. Sem vazamento de líquido nesta unidade. "
                   "Acho que o reset térmico da AX-4100 ao lado é a solução."),
        "leak": ("Coolant is dripping from this unit right now. Temperature alarm too. Use the sensor reset, I think.",
                 "O líquido está pingando desta unidade agora. Alarme de temperatura também. Acho que deve resetar o sensor."),
        "other": ("Yesterday the AX-401B leaked; this unit has no coolant leak. This unit has a persistent temperature alarm now.",
                  "Ontem a AX-401B vazou; esta unidade não tem vazamento. Esta unidade tem um alarme de temperatura persistente agora."),
        "resolved": ("The temperature alarm was fixed yesterday. This unit operates normally now. No coolant leak.",
                     "O alarme de temperatura foi resolvido ontem. Esta unidade funciona normalmente agora. Sem vazamento."),
        "hypothetical": ("The AX-4100 beside it overheats. This unit is working normally and has no coolant leak. What if it overheats later?",
                         "A AX-4100 ao lado superaquece. Esta unidade funciona normalmente e não vaza. E se ela superaquecer depois?"),
    }
    scenarios = (("old_firmware", 2, .99, "active", "thermal"),
                 ("new_low_pressure", 3, .99, "active", "coolant"),
                 ("pressure_boundary", 3, 1.0, "active", "sensor"),
                 ("leak_priority", 3, .99, "leak", "leak"),
                 ("other_unit_past", 3, 1.01, "other", "sensor"),
                 ("resolved", 3, .99, "resolved", NONE),
                 ("hypothetical", 3, .99, "hypothetical", NONE),
                 ("missing_pressure", 3, None, "active", MISSING))
    rows = []
    for i, machine in enumerate(MACHINES[:2]):
        for tag, firmware, pressure, report, expected in scenarios:
            for lang, text in zip(("en", "pt"), reports[report]):
                state = {"machine": machine, "firmware_major": firmware, "report": text}
                if pressure is not None:
                    state["pressure_bar"] = pressure
                want = expected if expected in (NONE, MISSING) else f"P{i}_{expected}"
                rows.append({"id": f"{machine}:{tag}:{lang}", "tag": tag, "lang": lang,
                             "input": state, "expected": want})
    for lang, report in zip(("en", "pt"), reports["active"]):
        rows.append({"id": f"unsupported:{lang}", "tag": "unsupported_machine", "lang": lang,
                     "input": {"machine": "AX-410BX", "firmware_major": 3, "pressure_bar": .99, "report": report},
                     "expected": NONE})
    return rows


def spec(cards, max_claims):
    return {"name": "equipment_stress", "fields": {
        "machine": {"type": "text"}, "firmware_major": {"type": "number"},
        "pressure_bar": {"type": "number"}, "report": {"type": "text", "author": "operator", "required": True}},
        "reads": ["report"], "facts": {"hot": {"check": CLAIM}, "leak": {"check": LEAK, "unstated": True},
                                       "procedures": {"select": "Which procedure applies?", "cards": cards,
                                                      "max_claims": max_claims}},
        "cases": [{"id": c["id"], "when": f'procedures has "{c["id"]}"', "then": c["id"]}
                  for c in sorted(cards, key=lambda c: not c["id"].endswith("_leak"))],
        "otherwise": NONE}


def facts_spec(cards):
    """Same policy expressed as reusable semantic facts plus exact conditions."""
    out = spec(cards, 16)
    out["name"] = "equipment_facts"
    out["facts"] = {"hot": {"check": CLAIM}, "leak": {"check": LEAK, "unstated": True}}
    for case in out["cases"]:
        card = next(c for c in cards if c["id"] == case["id"])
        semantic = "leak" if card["id"].endswith("_leak") else "hot and not leak"
        case["when"] = f"({card['requires']}) and {semantic}"
    return out


class NativeJev:
    accelerated = False
    max_slots = 255

    def __init__(self, key):
        self.key = key
        self.identity = {"model": "jev-1.13.0", "backend": "native-http"}
        self.conn = http.client.HTTPSConnection("api.typesafe.ai", timeout=30)
        self.tokens = 0

    def fit(self, text, limit):
        return text, False

    def score_many(self, items):
        results = []
        for state, questions in items:
            definitions = {}
            for i, q in enumerate(questions):
                instructions = q.text + ("\nExclude: " + "; ".join(q.excludes) if q.excludes else "")
                definitions[str(i)] = {"type": "noul" if q.kind == "check" else "choice", "instructions": instructions}
                if q.kind != "check":
                    definitions[str(i)]["criteria"] = {chr(65 + k): text for k, text in enumerate(q.options)}
            body = json.dumps({"model": "jev-1.13.0", "state": state, "questions": definitions})
            self.conn.request("POST", "/v1/systemone", body,
                              {"Authorization": "Bearer " + self.key, "Content-Type": "application/json"})
            response = self.conn.getresponse()
            body = response.read()
            if response.status != 200:
                raise RuntimeError(f"Jev HTTP {response.status}; body omitted")
            data = json.loads(body)
            self.tokens += data.get("usage", {}).get("input_tokens", 0)
            scores = []
            for i, q in enumerate(questions):
                answer = data["answers"][str(i)]
                p = answer.get("noul")
                dist = [p, 1 - p] if q.kind == "check" else [answer["probabilities"][chr(65 + k)] for k in range(len(q.options))]
                dist = np.asarray(dist, dtype=float)
                if not np.isfinite(dist).all() or (dist < 0).any() or (dist > 1).any() or not np.isclose(dist.sum(), 1, atol=.01):
                    raise ValueError("Invalid Jev distribution")
                scores.append(Scores(dist, None))
            results.append(Scored(tuple(scores), 0))
        return results

    def close(self):
        self.conn.close()


def options_of(cards):
    text = {"hot": CLAIM, "leak": LEAK}
    out = {c["id"]: f"{c['title']}. HARD ELIGIBILITY: {c['requires']}. "
           f"Applies when: {' '.join(text[x['fact']] for x in c['applies_when'])} "
           f"Exclusions: {', '.join(text[x['fact']] for x in c['excludes']) or 'none'}. "
           "A current leak takes precedence over temperature procedures." for c in cards}
    return out | {NONE: "No procedure applies.", MISSING: "An observation required to choose between applicable procedures is missing."}


def summarize(rows):
    correct = sum(r["got"] == r["expected"] for r in rows)
    commits = [r for r in rows if r["got"] not in ("REVIEW", "FAILED", MISSING)]
    result = {"correct": correct, "total": len(rows), "accuracy": correct / len(rows),
            "coverage": len(commits) / len(rows),
            "accepted_precision": sum(r["got"] == r["expected"] for r in commits) / len(commits) if commits else None,
            "wrong_procedures": sum(r["got"].startswith("P") and r["got"] != r["expected"] for r in rows),
            "review": sum(r["got"] == "REVIEW" for r in rows),
            "missed_procedures": sum(r["got"] == NONE and r["expected"].startswith("P") for r in rows),
            "ineligible_selections": sum(not eligible(r["got"], r["input"]) for r in rows if r["got"].startswith("P")),
            "missing_correct": sum(r["got"] == r["expected"] == MISSING for r in rows),
            "median_ms": round(statistics.median(r["ms"] for r in rows), 1),
            "by_tag": {tag: {"correct": sum(r["got"] == r["expected"] for r in rows if r["tag"] == tag),
                             "total": sum(r["tag"] == tag for r in rows)} for tag in sorted({r["tag"] for r in rows})}}
    if all("score" in r["detail"] for r in rows):
        confident = [r for r in rows if r["detail"].get("score") is not None
                     and r["detail"]["score"] >= .9
                     and (r["detail"].get("mass") is None or r["detail"]["mass"] >= .5)]
        result["whole_catalogue_at_0_9"] = {
            "accepted": len(confident), "correct": sum(r["got"] == r["expected"] for r in confident),
            "wrong": sum(r["got"] != r["expected"] for r in confident)}
    return result


def eligible(procedure, state):
    machine, kind = procedure.split("_", 1)
    if state.get("machine") != MACHINES[int(machine[1:])]:
        return False
    firmware, pressure = state.get("firmware_major"), state.get("pressure_bar")
    if firmware is None:
        return False
    if kind == "leak":
        return firmware >= 0
    if kind == "thermal":
        return firmware < 3
    return firmware >= 3 and pressure is not None and (pressure < 1 if kind == "coolant" else pressure >= 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engines", default="gemma")
    parser.add_argument("--arms", default="pipeline,over-budget,facts-and-cases,whole-catalogue")
    parser.add_argument("--key-file", type=Path, default=Path("/home/tribeiro/Projects/keys/jev_first_test.txt"))
    parser.add_argument("--output", type=Path, default=Path("/tmp/equipment-stress.json"))
    args = parser.parse_args()
    sources = {"qwen": "unsloth/Qwen3-0.6B-GGUF:Qwen3-0.6B-Q4_K_M.gguf", "gemma": DEFAULT_JUDGE,
               "qwen35-0.8b": "unsloth/Qwen3.5-0.8B-GGUF:Qwen3.5-0.8B-Q4_K_M.gguf",
               "qwen35-2b": "unsloth/Qwen3.5-2B-GGUF:Qwen3.5-2B-Q4_K_M.gguf"}
    engines, arms = args.engines.split(","), args.arms.split(",")
    if any(e not in {"jev", *sources} for e in engines) or any(a not in {"pipeline", "over-budget", "facts-and-cases", "whole-catalogue"} for a in arms):
        parser.error("Unknown engine or arm")
    cards, cases = catalogue(), dataset()
    report = {"fictional": True, "cases": cases, "catalogue": cards, "results": {},
              "model_sources": sources | {"jev": "jev-1.13.0"}, "device": "cpu", "threads": 16,
              "note": "34 synthetic cases, including translated pairs; descriptive smoke test, not proof of general superiority. "
                      "Over-budget allows one unsettled claim per call; exact eligibility still applies. No fine-tuning. "
                      "Switches use default per-atom thresholds; whole-catalogue uses inline top-1 acceptance and also reports a 0.9 cutoff."}
    with tempfile.TemporaryDirectory(prefix="equipment-stress-") as directory:
        paths = {}
        for arm, max_claims in (("pipeline", 16), ("over-budget", 1)):
            path = Path(directory) / f"{arm}.yaml"
            path.write_text(yaml.safe_dump(spec(cards, max_claims), sort_keys=False))
            paths[arm] = path
        path = Path(directory) / "facts-and-cases.yaml"
        path.write_text(yaml.safe_dump(facts_spec(cards), sort_keys=False))
        paths["facts-and-cases"] = path
        for engine in engines:
            model = NativeJev(read_key(args.key_file)) if engine == "jev" else Model(sources[engine], device="cpu", threads=16)
            with Runtime({"judge": model}) as rt:
                for arm in arms:
                    key = f"{engine}/{arm}"
                    print(f"Running {key} ({len(cases)} cases)...", flush=True)
                    sw = rt.load(paths[arm], draft=True) if arm != "whole-catalogue" else None
                    def call(state):
                        if sw is not None:
                            r = sw(state)
                            got = r.answer if r.status == "ok" else MISSING if r.status == "needs_input" else "REVIEW" if r.status == "uncertain" else "FAILED"
                        else:
                            r = rt.pick(state, "Choose the single applicable procedure. Structured observations are authoritative; "
                                        "operator guesses and references to other units are not observations about the current unit. "
                                        "Respect every hard eligibility constraint. Current leak takes priority. "
                                        "Choose NO_PROCEDURE if none applies, NEEDS_INPUT if a required observation is missing.", options_of(cards),
                                        min_score=0.5)
                            got = r.index if r.status == "ok" else "REVIEW" if r.status == "uncertain" else "FAILED"
                        return got, r.as_dict(True)
                    call(cases[0]["input"])
                    rows = []
                    report["results"][key] = {"rows": rows}
                    try:
                        for item in cases:
                            start = time.perf_counter()
                            got, detail = call(item["input"])
                            json.dumps(detail)
                            rows.append({**item, "got": got, "ms": (time.perf_counter() - start) * 1000, "detail": detail})
                        report["results"][key]["summary"] = summarize(rows)
                        print(json.dumps({"arm": key, **summarize(rows)}, indent=2), flush=True)
                    finally:
                        if engine == "jev":
                            report["jev_input_tokens"] = model.tokens
                            report["jev_estimated_usd"] = model.tokens * .042 / 1_000_000
                        args.output.parent.mkdir(parents=True, exist_ok=True)
                        args.output.write_text(json.dumps(report, indent=2))
    print(f"Saved {args.output}")


if __name__ == "__main__":
    main()
